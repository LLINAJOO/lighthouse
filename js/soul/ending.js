// ===== Farewell and credits =====
// ---------- farewell and the ending ----------
function presentAtFarewell() { const f = S.flags; return ['matvey'].concat(f.byeLida ? ['lida'] : [], f.byeSonya ? ['sonya'] : [], f.ny === 2 ? ['nyura'] : []); }
function farewell(cb) {
  const f = S.flags, L = [];
  L.push(['Матвей', f.stormRes === 'nets' ? 'Ну, бывай, смотритель. Сети мои целы — благодаря тебе. Помни: у тебя тут должник.' : f.eve6 === 'matvey' ? 'Ну, бывай. Уху нашу у костра я долго помнить буду.' : 'Ну, с богом, смотритель. За огнём пригляжу.']);
  if (f.byeLida) L.push(['Лида', f.stormRes === 'lida' ? 'Тот огонёк с пирса в шторм... Я теперь всегда буду на маяк оглядываться.' : f.gave_lida ? 'Саше ваше пахнет на всю почту! Пишите нам, я лично доставлю.' : 'Пишите нам! Я лично доставлю, обещаю.']);
  if (f.byeSonya) L.push(['Соня', f.eve6 === 'sonya' ? 'Портрет повешу у себя. Ты на нём смотришь на море.' : f.whalesSeen ? 'Я нарисую китов по твоему рассказу. И тебя рядом!' : 'Я нарисую, как ты уплываешь. Помаши мне!']);
  if (f.ny === 2) L.push(['Нюра', 'Еле успела! На «Чайке» прямо с базара. Смотритель-младший, кстати, передаёт привет. Пищит.']);
  if (f.pupFriend) L.push([HERO, 'У пирса вынырнула знакомая усатая голова. Тюленёнок пришёл проводить.']);
  if (catKept()) L.push([HERO, catName() + ', в катер. Поехали домой.']);
  L.push([HERO, presentAtFarewell().length >= 3 ? 'Спасибо вам. За всё.' : 'Спасибо, Матвей. За всё.']);
  say(L, cb);
}
function lifeLines() {
  const f = S.flags, out = [];
  out.push(f.stormRes === 'nets' ? 'Матвей до сих пор рыбачит сетями, которые вы спасли в шторм.' : f.stormRes === 'lida' ? 'Матвей сплёл новые сети. Говорит, старые всё равно были дырявые.' : 'Матвей ловит треску у пирса.');
  if (f.eve6 === 'matvey') out.push('Каждое лето он варит у пирса уху «как тогда, на прощание».');
  if ((f.boat | 0) >= 4) out.push('Он ходит на «Надежде» к Тюленьему камню.');
  out.push(f.stormRes === 'lida' ? 'Лида всё так же возит почту. В шторм она всегда ищет глазами маяк.' : 'Лида всё так же возит почту.');
  if (f.gave_lida) out.push('Её сумка с письмами до сих пор пахнет мелиссой.');
  out.push(f.eve6 === 'sonya' ? 'Портрет смотрителя на закате висит у Сони над кроватью.' : 'Соня дорисовала маяк.');
  if (f.gave_sonya) out.push('Ожерелье из ракушек она так и не снимает.');
  if (f.ny === 2) out.push('В журнале Нюры есть кайра по имени Смотритель.');
  if (f.pupFriend) out.push('Тюленёнок вырос и провожает лодки до самого пирса.');
  if (f.morse) out.push('Капитаны в округе знают: на этом маяке ответят.');
  out.push('Огонь горит каждую ночь.');
  return out;
}
function homeLines() {
  const f = S.flags, out = [];
  if (f.let3) out.push('Варя встречала на пристани в жёлтой куртке. Её было видно с середины залива.');
  else out.push('Варя и Наташа встречали на пристани.');
  const r = (f.reply1 || []).concat(f.reply2 || []);
  if (catKept()) out.push(catName() + ' первым спрыгнул на берег.' + (r.includes('cat') ? ' Варя узнала его сразу — по своему рисунку.' : ''));
  if (r.includes('seals')) out.push('Весь вечер Варя расспрашивала про тюленей.');
  else if (r.includes('matvey')) out.push('Привет от Матвея передан. Пирожок тоже, на словах.');
  return out;
}
